"""The prompt text the web app's quiz functions reuse (web/src/core/prompt-parts.json).

The hosted quiz writes and grades questions through the HintWise gateway from Netlify
functions written in TypeScript, without read tools: the code reaches the model as excerpts
fetched from GitHub at the analysis's pinned commit. The ladder, the one-fact and
no-identifier rules, the reference-answer rule and the grading rules are the CLI's own
(udebt/prompts.py), exported here as JSON so the two never drift apart.
`tests/test_hosted_parity.py` fails when the JSON in the web app is stale; regenerate it with

    python -m udebt.hosted.prompt_parts > web/src/core/prompt-parts.json
"""

from __future__ import annotations

import json
import sys
from typing import Any

from .. import ladder, prompts


def parts() -> dict[str, Any]:
    return {
        "comment": "Generated by `python -m udebt.hosted.prompt_parts` from udebt/prompts.py; "
        "do not edit by hand.",
        "ladder_block": prompts.ladder_block(),
        "one_fact": prompts.ONE_FACT,
        "no_identifiers": prompts.NO_IDENTIFIERS,
        "orientation_rule": prompts.ORIENTATION_RULE,
        "revealed_rule": prompts.REVEALED_RULE,
        "objective_rule": prompts.OBJECTIVE_RULE,
        "reference_rule": prompts.REFERENCE_RULE,
        "grade_rules": prompts.GRADE_RULES,
        "levels": {str(n): lv.name for n, lv in ladder.LEVELS.items()},
        "quiz_questions_schema": prompts.QUIZ_QUESTIONS_SCHEMA,
        "grade_schema": prompts.GRADE_SCHEMA,
    }


def text() -> str:
    return json.dumps(parts(), indent=1, ensure_ascii=False) + "\n"


if __name__ == "__main__":  # pragma: no cover
    sys.stdout.write(text())
